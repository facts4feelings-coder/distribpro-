// Offline database self-test: runs the real query shim + schema + triggers
// against an in-memory database.  Run with:  npm run test:db
import { supabase as s } from '../src/lib/localSupabase';
let failed = 0;
const ok = (name: string, cond: unknown, extra?: unknown) => { if (!cond) failed++; console.log(cond ? 'PASS' : 'FAIL', name, cond ? '' : JSON.stringify(extra)?.slice(0, 400)); };
(async () => {
  let r: any = await s.from('customers').insert({ name: 'Ali Traders', phone: '123', city: 'Lahore' }).select().single();
  ok('insert.select.single', r.data?.id && !r.error, r);
  const cid = r.data.id;
  r = await s.from('customers').insert([{ name: 'B' }, { name: 'C' }]);
  ok('insert no select -> data null', r.data === null && !r.error, r);
  r = await s.from('customers').select('*', { count: 'exact', head: true });
  ok('count head', r.count === 3 && r.data === null, r);
  r = await s.from('products').insert({ name: 'Soap', sale_price: 150.5, purchase_price: 100, stock_quantity: 10 }).select().single();
  ok('product numeric is number', typeof r.data?.sale_price === 'number', r);
  const pid = r.data.id;
  r = await s.from('customer_invoices').insert({ customer_id: cid, invoice_no: 'INV-0001', total: 301, paid_amount: 0, balance: 301, invoice_date: '2026-11-02' }).select().single();
  ok('invoice insert', !r.error, r);
  const iid = r.data?.id;
  ok('date shape', r.data?.invoice_date === '2026-11-02', r.data?.invoice_date);
  r = await s.from('customer_invoice_items').insert({ invoice_id: iid, product_id: pid, product_name: 'Soap', quantity: 2, unit_price: 150.5, total: 301 });
  ok('item insert', !r.error, r);
  r = await s.from('products').select('stock_quantity').eq('id', pid).single();
  ok('stock trigger ran (10->8)', Number(r.data?.stock_quantity) === 8, r);
  r = await s.from('customer_invoices').select('*, customers(name)').order('created_at', { ascending: false });
  ok('embed many-to-one', r.data?.[0]?.customers?.name === 'Ali Traders', r);
  r = await s.from('customer_invoice_items').select('product_id, unit_price, customer_invoices!inner(customer_id)').eq('customer_invoices.customer_id', cid).order('created_at', { ascending: false });
  ok('!inner + embedded filter', r.data?.length === 1 && r.data[0].unit_price === 150.5, r);
  r = await s.from('customer_invoice_items').select('product_id, customer_invoices!inner(customer_id)').eq('customer_invoices.customer_id', '00000000-0000-0000-0000-000000000000');
  ok('!inner filters out', r.data?.length === 0, r);
  r = await s.from('customer_invoices').update({ paid_amount: 301, balance: 0 }).eq('id', iid);
  ok('update.eq', !r.error, r);
  r = await s.from('customer_invoices').select('id, paid_amount, balance, status').eq('id', iid).single();
  ok('update applied + status trigger', r.data?.balance === 0, r);
  ok('status = paid', r.data?.status === 'paid', r);
  r = await s.from('settings').select('*').limit(1).maybeSingle();
  ok('maybeSingle', !r.error, r);
  r = await s.from('customers').select('id').eq('name', 'nobody').maybeSingle();
  ok('maybeSingle empty', r.data === null && !r.error, r);
  r = await s.from('customers').select('id').eq('name', 'nobody').single();
  ok('single empty -> error', !!r.error, r);
  r = await s.from('customers').select('id, name').in('name', ['B', 'C']).order('name');
  ok('in + order', r.data?.length === 2 && r.data[0].name === 'B', r);
  r = await s.from('customers').select('*').or('name.ilike.%ali%,phone.eq.999');
  ok('or ilike', r.data?.length === 1, r);
  r = await s.from('customers').select('*').gte('created_at', '2000-01-01').lt('created_at', '2100-01-01');
  ok('gte/lt', r.data?.length === 3, r);
  r = await s.from('customer_invoices').select('*, customers(*)').eq('customer_id', cid);
  ok('embed *', r.data?.[0]?.customers?.city === 'Lahore', r);
  r = await s.from('backup_history').insert({ kind: 'manual', file_name: 'x.json', size_bytes: 10, table_counts: { customers: 3 } }).select().single();
  ok('jsonb insert', r.data?.table_counts?.customers === 3, r);
  r = await s.from('customers').upsert([{ id: cid, name: 'Ali Traders 2' }]);
  ok('upsert no onConflict (pk)', !r.error, r);
  r = await s.from('customers').select('name').eq('id', cid).single();
  ok('upsert updated', r.data?.name === 'Ali Traders 2', r);
  const { data: up } = await s.from('user_permissions').select('*').limit(1);
  r = await s.from('customer_invoice_items').delete().eq('invoice_id', iid);
  ok('delete.eq', !r.error, r);
  r = await s.from('products').select('stock_quantity').eq('id', pid).single();
  ok('stock restored on delete (8->10)', Number(r.data?.stock_quantity) === 10, r);
  r = await s.from('customers').delete().eq('name', 'C').select();
  ok('delete.select returns rows', r.data?.length === 1, r);
  r = await s.from('customers').select('nonexistent_col');
  ok('bad column -> error not crash', !!r.error, r);
  void up;
  console.log(failed ? `\n${failed} test(s) FAILED` : '\nAll database tests passed');
  process.exit(failed ? 1 : 0);
})().catch((e) => { console.error('CRASH', e); process.exit(1); });
